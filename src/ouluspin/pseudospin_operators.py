class GeneralVectorOperatorMatrix:
    """A class to store a set of matrices corresponding to the different components
    of a vector operator. This class is mostly intended as a simple interace for
    handling a set of operator components.

    The components of the operator are assumed Hermitian!

    Arguments
    ---------
    matrix_list : list of array of complex128
        A matrix representations of the operator components.

    Optional arguments
    ------------------
    diagonalize_operator_matrix : boolean
        Whether to diagonalize the operator upon class initiation. Default is True.
    translate_eigenvalues : boolean
        Whether to add a constant shift to all eigenvalues so that the lowest eigenvalue
        is equal to zero. This makes sense when the operator is the Hamiltonian, but
        should not be used in other cases.

    Attributes
    ----------
    diagonalize_operator_matrix : boolean
        Whether to diagonalize the operator upon class initiation. Default is True.
    translate_eigenvalues : boolean
        Whether to add a constant shift to all eigenvalues so that the lowest eigenvalue
        is equal to zero. This makes sense when the operator is the Hamiltonian, but
        should not be used in other cases.
    operator_list : list of GeneralOperatorMatrix
        List of the operator components.
    n_operators : int
        The number of components in the vector operator. This is usually three as the
        most common type of a vector operator is a Cartesian vector operator.
    n_basis : int
        Dimension of the operator matrices.

    Private methods
    ---------------

    Public methods
    --------------
    matrix_list() : list of array of complex128
        Return a list of matrix representations of the different components of the vector
        operator.

    Class methods
    -------------
    run_tests(print_output=True) : boolean
        Initiate the class and run a set of internal tests. Return True if all
        tests passed.
    """

    def matrix_list(self):
        """Return a list of matrix representations of the different components of the
        vector operator.
        """
        tmp_list = []
        for i in range(0,self.n_operators):
            tmp_list.append(self.operator_list[i].matrix)

        return tmp_list


    def eigenvalue_table(self, print_limit=None):
        """Return a table of the eigenvalues of the three Cartesian
        components of the vector operator as an instance of ResultTable.
        The components are tabulated one below the other in sections; the
        rows are those of the eigenvalue table of the individual components.

        Optional arguments
        ------------------
        print_limit : float or None
            Eigenvalues above this value are not tabulated. Default is
            None, in which case all the eigenvalues are tabulated.
        """
        index_to_component = {0 : "x", 1 : "y", 2 : "z"}

        rows           = []
        column_headers = None
        formats        = None

        for i in range(0,self.n_operators):
            component_table = self.operator_list[i].eigenvalue_table(print_limit=print_limit)

            rows.append("Vector operator component {0}"
                        .format(index_to_component.get(i,str(i))))
            rows.extend(component_table.rows)

            if i == 0 and len(component_table.column_headers) > 0:
                column_headers = component_table.column_headers
                formats        = component_table.formats

        return result_table.ResultTable(rows,
                                        column_headers=column_headers,
                                        title="LIST OF EIGENVALUES OF THE VECTOR OPERATOR COMPONENTS",
                                        formats=formats,
                                        table_type='eigenvalues')


    def __repr__(self):
        """Return a human-readable summary of the vector operator matrices."""
        return str(self.eigenvalue_table())
    

    def __init__(self, matrix_list,
                 diagonalize_operator_matrix=False,
                 translate_eigenvalues=False):
        """Construct the list of instances of GeneralOperatorMatrix."""

        self.diagonalize_operator_matrix = diagonalize_operator_matrix
        self.translate_eigenvalues = translate_eigenvalues

        self.n_operators = len(matrix_list)

        self.operator_list = []

        for matrix in iter(matrix_list):
            self.operator_list.append(GeneralOperatorMatrix(matrix,
                                                            diagonalize_operator_matrix=self.diagonalize_operator_matrix,
                                                            translate_eigenvalues=self.translate_eigenvalues))

        self.n_basis = self.operator_list[0].n_basis

        if (not self.n_basis == self.operator_list[1].n_basis) or (not self.n_basis == self.operator_list[2].n_basis):
            print("ERROR in GeneralVectorOperatorMatrix.")
            print("Error: Inconsistent operator dimensions.")
            print("Error termination.")
            sys.exit(1)


    @classmethod
    def run_tests(cls, print_output=True):
        """Initiate the class and run a set of tests on the class constructor
        and the class methods. Return True if all tests passed and False
        otherwise.

        Optional arguments
        ------------------
        print_output : boolean
            Whether to print the outcome of each test. Default is True.
        """
        from ouluspin import _debug as debug_output

        result_list = []
        def check(test_name,condition):
            result_list.append(debug_output.test_check('GeneralVectorOperatorMatrix',
                                                       test_name,condition,print_output))

        # The Cartesian components of an S = 1 spin operator.
        spin_matrix_list = debug_output.spin_matrices(2)
        vector_operator = cls(spin_matrix_list,
                              diagonalize_operator_matrix=True,
                              translate_eigenvalues=False)

        check('dimensions',
              (vector_operator.n_operators == 3) and (vector_operator.n_basis == 3))
        check('matrix list contents',
              all(np.allclose(a,b) for a, b in zip(vector_operator.matrix_list(),
                                                   spin_matrix_list)))
        check('eigenvalues of S_z',
              np.allclose(vector_operator.operator_list[2].eigenvalues,[-1.0,0.0,1.0]))
        check('string representation renders', len(str(vector_operator)) > 0)

        return debug_output.test_summary('GeneralVectorOperatorMatrix',
                                         result_list,print_output)
