    @classmethod
    def run_tests(cls, print_output=True):
        """Initiate the class and run a set of tests on the class constructor
        and the class methods. Return True if all tests passed and False
        otherwise.

        Optional arguments
        ------------------
        print_output : boolean
            Whether to print the outcome of each test. Default is True.
        """
        from ouluspin import units
        from ouluspin import _debug as debug_output

        result_list = []
        def check(test_name,condition):
            result_list.append(debug_output.test_check('PseudoSpinVectorOperator',
                                                       test_name,condition,print_output))

        tmp_units  = units.EnergyUnitSystem('wavenumber')
        pseudospin = 3   # S = 3/2

        # A spin vector operator given as a mixed Cartesian--spherical tensor.
        mixed_tensor = tensors.MixedCartesianIwaharaChibotaruSphericalTensor\
                              .from_one_site_isotropic_operator(1.0,pseudospin)

        vector_operator = cls(PseudoSpinBasis([pseudospin]),[mixed_tensor],
                              tmp_units,
                              diagonalize_operator_matrix=False,
                              store_operator_matrix=True)

        check('number of components', vector_operator.n_operators == 3)

        matrix_list = vector_operator.matrix_list()
        check('matrix list dimensions',
              (len(matrix_list) == 3) and (matrix_list[0].shape == (4,4)))

        # The components must obey the angular momentum commutation relation
        # [S_x,S_y] = i*S_z.
